#!/usr/bin/env python3
"""Regenerate KCC's pinned Unicode 15.1 identifier/normalization tables."""
import unicodedata as ud
from pathlib import Path
assert ud.unidata_version == '15.1.0', ud.unidata_version
MAX = 0x110000

def ranges(values):
    result=[]
    for n in values:
        if result and result[-1][1] + 1 == n:
            result[-1][1]=n
        else:
            result.append([n,n])
    return result
start=ranges(i for i in range(128,MAX) if chr(i).isidentifier())
cont=ranges(i for i in range(128,MAX) if ('A'+chr(i)).isidentifier())
ccc=[(i,ud.combining(chr(i))) for i in range(MAX) if ud.combining(chr(i))]
decomp=[]; comp=[]
for i in range(MAX):
    ch=chr(i)
    nfd=ud.normalize('NFD',ch)
    if nfd != ch and not 0xac00 <= i <= 0xd7a3:
        decomp.append((i,[ord(c) for c in nfd]))
    d=ud.decomposition(ch)
    if d and not d.startswith('<'):
        seq=[int(x,16) for x in d.split()]
        if len(seq)==2 and ud.normalize('NFC',''.join(chr(x) for x in seq))==ch:
            comp.append((*seq,i))
comp.sort()
out=['/* Generated by scripts/generate_unicode_identifiers.py; Unicode 15.1.0. */',
     'struct unicode_range { uint32_t lo, hi; };',
     'struct unicode_ccc { uint32_t cp; unsigned char value; };',
     'struct unicode_decomposition { uint32_t cp, values[4]; unsigned char length; };',
     'struct unicode_composition { uint32_t first, second, result; };']
def arr(name,typ,lines):
    out.append(f'static const struct {typ} {name}[] = {{')
    out.extend('    '+line+',' for line in lines)
    out.append('};')
arr('unicode_xid_start','unicode_range',(f'{{0x{a:x}, 0x{b:x}}}' for a,b in start))
arr('unicode_xid_continue','unicode_range',(f'{{0x{a:x}, 0x{b:x}}}' for a,b in cont))
arr('unicode_combining_class','unicode_ccc',(f'{{0x{x:x}, {y}}}' for x,y in ccc))
arr('unicode_decompositions','unicode_decomposition',(f'{{0x{x:x}, {{{", ".join(f"0x{v:x}" for v in seq)}}}, {len(seq)}}}' for x,seq in decomp))
arr('unicode_compositions','unicode_composition',(f'{{0x{a:x}, 0x{b:x}, 0x{c:x}}}' for a,b,c in comp))
Path('src/unicode_identifiers.inc').write_text('\n'.join(out)+'\n')
print(f'generated: {len(start)} start ranges, {len(cont)} continue ranges, {len(ccc)} combining classes, {len(decomp)} decompositions, {len(comp)} compositions')
